def try_web(ep):
    title = ep["title"]
    short = title if len(title) <= 80 else title[:80].rsplit(" ", 1)[0]
    show = ep["show"]
    show_s = show.split(" (")[0].split(" |")[0].split(" - ")[0]
    queries = [
        f'"{short}" "{show_s}" transcript',
        f'"{short}" transcript site:podscripts.co OR site:podscribe.ai OR site:listennotes.com OR site:snipd.com',
        f'"{show_s}" "{short}" full text transcript',
    ]
    for qi, q in enumerate(queries):
        for ename, eng in (("bing", bing), ("ddg", ddg)):
            try:
                results = eng(q)
            except Exception:
                results = []
            print(f"    Q{qi+1}/{ename}: {len(results)} hits", flush=True)
            for r in results[:3]:
                u = r["url"]
                if any(h in u for h in SKIP_HOSTS):
                    continue
                try:
                    page, ct = fetch(u, timeout=25)
                except Exception:
                    continue
                txt = html_to_text(page)
                if not looks_like_transcript(txt):
                    continue
                host = urllib.parse.urlparse(u).netloc.lower()
                trust = any(h in host for h in TRUSTED)
                ov = score(ep["title"], txt[:6000])
                # reject unrelated pages (wiki/dictionary/etc) — require title evidence
                if not (trust and ov >= 0.30) and not (ov >= 0.55 and len(txt) > 6000):
                    print(f"    reject {host} ov={ov:.2f} {len(txt)}c", flush=True)
                    continue
                return txt[:600000], "web", u
    return None, None, None


def work(ep):
    k = key_for(ep)
    path = os.path.join(TDIR, k + ".json")
    if os.path.exists(path):
        try:
            old = json.load(open(path))
            if old.get("transcript_source"):
                return old
        except Exception:
            pass
    rec = dict(ep)
    txt, src, ref = try_rss(ep)
    if not txt:
        txt, src, ref = try_youtube(ep)
    if not txt:
        txt, src, ref = try_web(ep)
    if not txt:
        d = re.sub(r"\s+", " ", html_to_text(ep.get("description_html") or "")).strip()
        if d:
            txt, src, ref = d, "description", "rss_description"
    rec["transcript"] = txt or ""
    rec["transcript_source"] = src
    rec["transcript_ref"] = ref
    with open(path, "w") as f:
        json.dump(rec, f, indent=1, ensure_ascii=False)
    if txt:
        with open(os.path.join(TDIR, k + ".txt"), "w") as f:
            f.write(txt)
    return rec


def main():
    cand = json.load(open(CAND))
    eps = cand["episodes"]
    only = sys.argv[1:] 
    if only:
        eps = [e for e in eps if key_for(e) in only or e["guid"] in only]
    print(f"episodes: {len(eps)}", flush=True)
    done = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as ex:
        futs = {ex.submit(work, e): e for e in eps}
        for fut in concurrent.futures.as_completed(futs):
            ep = futs[fut]
            try:
                rec = fut.result()
            except Exception as e:
                print(f"[ERR] {ep['show']} :: {e}", flush=True)
                rec = dict(ep, transcript="", transcript_source=None)
            done.append(rec)
            print(f"[{(rec.get('transcript_source') or 'NONE'):20s}] {len((rec.get('transcript') or '').split()):6d}w "
                  f"{rec['show'][:32]:32s} | {rec['title'][:52]}", flush=True)
    got = sum(1 for r in done if r.get("transcript_source"))
    print(f"\n{got}/{len(done)} with transcripts")


if __name__ == "__main__":
    main()
